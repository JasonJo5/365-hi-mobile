function t(key, lang) {
    const dict = translations[lang || (document.documentElement.getAttribute('lang')) || 'en'] || translations.en;
    return dict[key] !== undefined ? dict[key] : (translations.en[key] !== undefined ? translations.en[key] : key);
}

function setLanguage(lang) {
    const dict = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] === undefined) return;
        if (el.getAttribute('data-i18n-html') === 'true') {
            el.innerHTML = dict[key];
        } else {
            el.textContent = dict[key];
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] === undefined) return;
        el.setAttribute('placeholder', dict[key]);
    });
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
        const active = btn.getAttribute('data-lang-btn') === lang;
        btn.classList.toggle('text-primary', active);
        btn.classList.toggle('bg-primary/15', active);
    });
    document.documentElement.setAttribute('lang', lang);
    try { localStorage.setItem('site_lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('site:languagechange', { detail: { lang: lang } }));
}

document.addEventListener('DOMContentLoaded', function () {
    let saved = 'en';
    try { saved = localStorage.getItem('site_lang') || 'en'; } catch (e) {}
    setLanguage(saved);
});

// ===== Light / Dark theme =====
function applyTheme(theme) {
    const root = document.documentElement;
    const icon = document.getElementById('theme-toggle-icon');
    if (theme === 'light') {
        root.classList.add('light');
    } else {
        root.classList.remove('light');
    }
    if (icon) {
        icon.textContent = theme === 'light' ? 'light_mode' : 'dark_mode';
    }
    try { localStorage.setItem('site_theme', theme); } catch (e) {}
}

function toggleTheme() {
    const isLight = document.documentElement.classList.contains('light');
    applyTheme(isLight ? 'dark' : 'light');
}

